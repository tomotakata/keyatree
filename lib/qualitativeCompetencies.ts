export const COMPETENCY_ITEMS: CompetencyItem[] = raw.flatMap((group) =>
  group.items.map(([no, text]) => ({ no, band: group.band, category: group.category, text }))
);

const BAND_ORDER: CompetencyBand[] = ["S1", "S2", "L1", "L2", "M1", "M2", "M3"];

/** スタッフのグレード文字列から能力項目の帯（band）を判定する。 */
export function bandForGrade(grade: string): CompetencyBand | null {
  const g = (grade || "").toUpperCase().replace(/\s/g, "");
  // 正規のバンド表記に一致
  for (const b of BAND_ORDER) {
    if (g === b || g.includes(b)) return b;
  }
  // デモ用の旧グレード表記を近いバンドへマッピング
  if (/^E[12]$/.test(g) || g === "J1") return "S1";
  if (g === "J2" || g === "J3") return "S2";
  if (g === "S3") return "L1";
  return null;
}

/** No.付きの表示ラベルを作る（例: No.001 誠実な対応 ／ 謙虚に振る舞った…）。 */
export function competencyLabel(item: CompetencyItem): string {
  return `No.${String(item.no).padStart(3, "0")} ${item.category} ／ ${item.text}`;
}

/** グレードに応じた能力項目の一覧を返す。判定不能なら全項目を返す（空にしない）。 */
export function competencyItemsForGrade(grade: string): CompetencyItem[] {
  const band = bandForGrade(grade);
  if (!band) return COMPETENCY_ITEMS;
  return COMPETENCY_ITEMS.filter((item) => item.band === band);
}
